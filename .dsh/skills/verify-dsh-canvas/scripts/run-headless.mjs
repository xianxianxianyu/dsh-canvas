#!/usr/bin/env node
// Run one task in headless DSH with this checkout of dsh-canvas, keep every byte of the run under
// one evidence directory, and print the session id plus each canvas_check result verbatim.
//
//   run-headless.mjs [--model deepseek-flash|deepseek-v4-pro] [--no-browser] [--name <run>]
//                    [--timeout <seconds>] [--cwd <dir>] [--canvas-root <dir>] <prompt | ->
//
// The run directory is $CANVAS_VERIFY_OUT/<run> (default root /tmp/dsh-canvas-verify):
//   prompt.txt, events.ndjson (dsh --json), stderr.log, final.txt, canvas-check.txt,
//   canvas-comment.txt, summary.json, check-<n>.png (the picture each canvas_check attached),
//   work/ (the session's cwd), state/ (session store, canvas root, attachment store), run.patch.yml.
// --cwd and --canvas-root continue a multi-turn journey such as comments: the session works in an
// earlier run's work/, and canvas reads and writes a comment store that a dev server shares. Both
// must be existing directories inside the evidence root, so a run never writes outside it.
// An existing run directory is never reused, so earlier evidence is never overwritten.
// Exit status: 0 when the turn completed, 1 when it did not, 2 for usage or setup errors.

import { spawnSync } from 'node:child_process'
import { closeSync, copyFileSync, existsSync, mkdirSync, openSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { zstdDecompressSync } from 'node:zlib'

export const PROFILE = 'canvas-e2e'
export const DSH_BIN = '/Applications/DeepSeek Harness.app/Contents/Resources/runtime/cli/bin'
export const REPO = realpathSync(resolve(dirname(fileURLToPath(import.meta.url)), '../../../..'))
export const OUT = process.env.CANVAS_VERIFY_OUT || '/tmp/dsh-canvas-verify'
const USAGE = 'usage: run-headless.mjs [--model deepseek-flash|deepseek-v4-pro] [--no-browser] [--name <run>] [--timeout <seconds>] [--cwd <dir>] [--canvas-root <dir>] <prompt | ->'

/** The environment every dsh call gets: the CLI's bin only (never runtime/bin), no inherited DSH_HOME. */
export function dshEnv() {
  const env = { ...process.env, PATH: `${DSH_BIN}:${process.env.PATH}` }
  delete env.DSH_HOME
  return env
}

/** The profile directory, as dsh resolves it once DSH_HOME is unset. */
export function profileDir(name) {
  return join(homedir(), '.dsh', 'profiles', name)
}

/** Whether the profile's dsh-canvas dependency resolves to this checkout. */
export function linkState(name) {
  const dir = profileDir(name)
  if (!existsSync(dir)) return { ok: false, missing: true, detail: `profile ${name} does not exist` }
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const spec = manifest.dependencies?.['dsh-canvas']
  if (!spec) return { ok: false, unlinked: true, detail: `profile ${name} has no dsh-canvas dependency` }
  let target
  try { target = realpathSync(join(dir, 'node_modules', 'dsh-canvas')) } catch { target = undefined }
  if (target !== REPO) return { ok: false, detail: `profile ${name} links ${spec} (resolves to ${target ?? 'nothing'}), not this checkout ${REPO}` }
  return { ok: true, detail: `profile ${name} links this checkout` }
}

function dsh(args, options = {}) {
  return spawnSync('dsh', args, { env: dshEnv(), encoding: 'utf8', ...options })
}

function fail(message, code = 2) {
  console.error(`run-headless: ${message}`)
  process.exit(code)
}

/** Create the headless profile on first use and link this checkout; never steal another checkout's link. */
function ensureProfile() {
  let state = linkState(PROFILE)
  if (state.missing) {
    const created = dsh(['--profile', PROFILE, '--from-default-profile', 'headless', '--dump-config'])
    if (created.status !== 0) fail(`could not create profile ${PROFILE}:\n${created.stderr}`)
    state = linkState(PROFILE)
  }
  if (state.unlinked) {
    const added = dsh(['plugin', '--profile', PROFILE, 'add', `link:${REPO}`])
    if (added.status !== 0) fail(`could not link ${REPO} into ${PROFILE}:\n${added.stderr}`)
    state = linkState(PROFILE)
  }
  if (!state.ok) fail(`${state.detail}\nRelink it on purpose with: dsh plugin --profile ${PROFILE} add link:${REPO}`)
}

/**
 * The run's only patch: account auth on (the headless template disables it), the model, the
 * present tool (absent from the headless template), and every store moved into the run directory.
 */
function runPatch({ model, state, canvasRoot, noBrowser }) {
  return `# Generated by run-headless.mjs for one run.
- id: credentials
  disabled: false
- id: authorization
  disabled: false
- id: deepseek-account
  disabled: false
- id: agent-default-model
  name: '@deepseek-ai/dsh-agent-default-model'
  config:
    provider: deepseek-account
    model: ${model}
    reasoningEffort: high
- id: session-persistence-jsonl
  name: '@deepseek-ai/dsh-session-persistence-jsonl'
  config:
    root: ${JSON.stringify(join(state, 'sessions'))}
- id: storage-json
  name: '@deepseek-ai/dsh-storage-json'
  config:
    root: ${JSON.stringify(join(state, 'storages'))}
- id: attachment-local
  name: '@deepseek-ai/dsh-attachment-local'
  config:
    dshHome: ${JSON.stringify(join(state, 'home'))}
- id: canvas
  config:
    root: ${JSON.stringify(canvasRoot)}${noBrowser ? `
    browserPath: ${JSON.stringify(join(state, 'no-such-chrome'))}` : ''}
- insert:
    - id: present
      name: '@deepseek-ai/dsh-tool-present'
`
}

function parseArgs(argv) {
  const options = { model: 'deepseek-flash', noBrowser: false, name: undefined, timeout: 600, cwd: undefined, canvasRoot: undefined }
  const rest = []
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (arg === '--model') options.model = argv[++i]
    else if (arg === '--no-browser') options.noBrowser = true
    else if (arg === '--name') options.name = argv[++i]
    else if (arg === '--timeout') options.timeout = Number(argv[++i])
    else if (arg === '--cwd') options.cwd = argv[++i]
    else if (arg === '--canvas-root') options.canvasRoot = argv[++i]
    else if (arg === '-h' || arg === '--help') { console.log(USAGE); process.exit(0) }
    else rest.push(arg)
  }
  if (!options.model || !/^[\w.-]+$/.test(options.model)) fail('--model needs a model id such as deepseek-flash')
  if (options.name !== undefined && !/^[\w.-]+$/.test(options.name)) fail('--name may use letters, digits, ".", "_" and "-"')
  if (!(options.timeout > 0)) fail('--timeout needs a positive number of seconds')
  for (const [flag, dir] of [['--cwd', options.cwd], ['--canvas-root', options.canvasRoot]]) {
    if (dir === undefined) continue
    if (!existsSync(dir)) fail(`${flag} ${dir} does not exist`)
    if (!realpathSync(dir).startsWith(`${realpathSync(OUT)}/`)) fail(`${flag} must be a directory inside the evidence root ${OUT}`)
  }
  const prompt = rest.length === 1 && rest[0] === '-' ? readFileSync(0, 'utf8') : rest.join(' ')
  if (!prompt.trim()) fail(`give the task as arguments, or - to read it from stdin\n${USAGE}`)
  return { ...options, prompt }
}

function stamp() {
  return new Date().toISOString().replace(/[-:]/g, '').replace(/\..*/, '').replace('T', '-')
}

/** callId → content blocks of its persisted tool result, read from the run's session store. */
function storedResults(state, sessionId) {
  const results = new Map()
  const root = join(state, 'sessions')
  if (!sessionId || !existsSync(root)) return results
  const log = readdirSync(root, { withFileTypes: true, recursive: true })
    .find(entry => entry.isFile() && entry.name === 'session.v4.jsonl.zstd' && entry.parentPath.endsWith(`/${sessionId}`))
  if (!log) return results
  for (const line of zstdDecompressSync(readFileSync(join(log.parentPath, log.name))).toString('utf8').split('\n')) {
    if (!line.includes('"tool/result"')) continue
    const event = JSON.parse(line)
    if (event.type === 'tool/result') results.set(event.data.message.toolCallId, event.data.message.content)
  }
  return results
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  const run = join(OUT, options.name ?? `headless-${stamp()}`)
  if (existsSync(run)) fail(`${run} already exists; pick another --name (evidence is never overwritten)`)
  if (!existsSync(join(DSH_BIN, 'dsh'))) fail(`no dsh CLI at ${DSH_BIN}; install DeepSeek Harness.app`)
  ensureProfile()

  const work = options.cwd === undefined ? join(run, 'work') : resolve(options.cwd)
  const state = join(run, 'state')
  const canvasRoot = options.canvasRoot === undefined ? join(state, 'canvas') : resolve(options.canvasRoot)
  // With --cwd and --canvas-root both given, nothing else would create the run directory.
  for (const dir of [run, work, canvasRoot]) mkdirSync(dir, { recursive: true })
  const patch = join(run, 'run.patch.yml')
  writeFileSync(patch, runPatch({ model: options.model, state, canvasRoot, noBrowser: options.noBrowser }))
  writeFileSync(join(run, 'prompt.txt'), options.prompt)

  const stdout = openSync(join(run, 'events.ndjson'), 'w')
  const stderr = openSync(join(run, 'stderr.log'), 'w')
  const started = Date.now()
  const child = dsh(['--profile', PROFILE, '--patch', patch, '--json', options.prompt], {
    cwd: work, stdio: ['ignore', stdout, stderr], timeout: options.timeout * 1000,
  })
  closeSync(stdout)
  closeSync(stderr)

  const events = readFileSync(join(run, 'events.ndjson'), 'utf8').split('\n').filter(Boolean).map(line => JSON.parse(line))
  const sessionId = events.find(event => event.type === 'session')?.sessionId
  const final = events.findLast(event => event.type === 'final')
  const calls = new Map(events.filter(event => event.type === 'tool_call').map(event => [event.callId, event]))
  const stored = storedResults(state, sessionId)
  const checks = []
  const presented = []
  const comments = []
  for (const result of events.filter(event => event.type === 'tool_result')) {
    const call = calls.get(result.callId)
    if (call?.tool === 'present') presented.push(result.result)
    if (call?.tool === 'canvas_comment') comments.push({ n: comments.length + 1, input: call.input, status: result.status, result: result.result })
    if (call?.tool !== 'canvas_check') continue
    const n = checks.length + 1
    const images = []
    for (const block of stored.get(result.callId) ?? []) {
      if (block.type !== 'image') continue
      const hex = block.attachment.attachmentId.replace(/^sha256:/, '')
      const file = join(run, `check-${n}${images.length ? `-${images.length + 1}` : ''}.png`)
      copyFileSync(join(state, 'home', 'attachments', 'v1', 'objects', hex.slice(0, 2), hex), file)
      images.push({ file, width: block.attachment.width, height: block.attachment.height, sha256: hex })
    }
    checks.push({ n, input: call.input, status: result.status, result: result.result, images })
  }

  const stderrText = readFileSync(join(run, 'stderr.log'), 'utf8')
  const summary = {
    run, sessionId, model: options.model, browser: options.noBrowser ? 'missing on purpose' : 'discovered', cwd: work, canvasRoot,
    exit: child.status, signal: child.signal, seconds: Math.round((Date.now() - started) / 1000),
    final: final?.reason ?? null, signInRequired: stderrText.includes('ACCOUNT_SIGN_IN_REQUIRED'), checks, comments, presented,
  }
  writeFileSync(join(run, 'summary.json'), `${JSON.stringify(summary, null, 2)}\n`)
  writeFileSync(join(run, 'final.txt'), final?.text ?? '')
  const report = checks.map(check => [
    `--- canvas_check #${check.n} ${check.status} ${JSON.stringify(check.input)}`,
    check.result,
    ...check.images.map(image => `[image ${image.width}×${image.height} → ${image.file}]`),
  ].join('\n')).join('\n\n')
  writeFileSync(join(run, 'canvas-check.txt'), report ? `${report}\n` : '')
  const commentReport = comments.map(call => `--- canvas_comment #${call.n} ${call.status} ${JSON.stringify(call.input)}\n${call.result}`).join('\n\n')
  writeFileSync(join(run, 'canvas-comment.txt'), commentReport ? `${commentReport}\n` : '')

  console.log(`run      ${run}`)
  console.log(`session  ${sessionId ?? '(none: dsh never opened a session; see stderr.log)'}`)
  console.log(`model    ${options.model}${options.noBrowser ? ' (browserPath points at a missing file)' : ''}`)
  console.log(`final    ${final ? JSON.stringify(final.reason) : '(no final event)'}  exit=${child.status ?? child.signal} ${summary.seconds}s`)
  if (summary.signInRequired) console.log('auth     ACCOUNT_SIGN_IN_REQUIRED: sign in to DeepSeek in the desktop app, then rerun')
  for (const line of presented) console.log(`present  ${line}`)
  console.log(report ? `\n${report}` : '\n(no canvas_check calls)')
  if (commentReport) console.log(`\n${commentReport}`)
  process.exit(child.status === 0 && final?.reason?.kind === 'completed' ? 0 : 1)
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main()
